const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const request = require('supertest');
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pocketwise-test-'));
process.env.DATABASE_PATH = path.join(tempDir, 'test.sqlite');
process.env.SESSION_SECRET = 'test-session-secret-with-enough-entropy';
const { app, db } = require('../server');
const today = new Date().toISOString().slice(0,10);
const month = today.slice(0,7);
after(() => { db.close(); fs.rmSync(tempDir, { recursive: true, force: true }); });

test('auth, transaction CRUD, ownership, budgets, goals, and report export', async () => {
  const owner = request.agent(app);
  const other = request.agent(app);
  const signup = await owner.post('/api/auth/register').send({ name: 'Asha Rao', email: 'asha@example.test', password: 'a-long-test-password' });
  assert.equal(signup.status, 201);
  assert.equal((await owner.get('/api/auth/me')).status, 200);
  const login = request.agent(app);
  assert.equal((await login.post('/api/auth/login').send({email:'asha@example.test',password:'a-long-test-password'})).status, 200);
  assert.equal((await request(app).post('/api/auth/login').send({email:'asha@example.test',password:'wrong-password'})).status, 401);
  assert.equal((await request(app).post('/api/transactions').send({ title: 'No auth', amount: 100, type: 'expense', category: 'Food and dining', paymentMethod: 'UPI', date: today })).status, 401);
  assert.equal((await other.post('/api/auth/register').send({ name: 'Ravi Das', email: 'ravi@example.test', password: 'another-long-password' })).status, 201);
  assert.equal((await other.get('/api/transactions')).body.transactions.length, 0);

  const created = await owner.post('/api/transactions').send({ title: 'Lunch', amount: 450.5, type: 'expense', category: 'Food and dining', paymentMethod: 'UPI', date: today, notes: 'Team lunch' });
  assert.equal(created.status, 201);
  const txId = created.body.transaction.id;
  assert.equal(created.body.transaction.amount, 450.5);
  assert.equal((await other.get('/api/transactions')).body.transactions.length, 0);
  assert.equal((await owner.put(`/api/transactions/${txId}`).send({ title: 'Dinner', amount: 500, type: 'expense', category: 'Food and dining', paymentMethod: 'UPI', date: today })).status, 200);
  assert.equal((await owner.post('/api/transactions').send({ title: 'Bad date', amount: 10, type: 'expense', category: 'Food and dining', paymentMethod: 'Cash', date: '2026-02-31' })).status, 400);

  assert.equal((await owner.post('/api/budgets').send({ category: 'Food and dining', amount: 1000, month })).status, 201);
  const budgets = await owner.get(`/api/budgets?month=${month}`);
  assert.equal(budgets.body.budgets[0].spent, 500);
  assert.equal(budgets.body.budgets[0].remaining, 500);
  assert.equal((await owner.post('/api/transactions').send({title:'Bus fare',amount:60,type:'expense',category:'Transport',paymentMethod:'Cash',date:today})).status,201);
  const budgetTotals = await owner.get(`/api/budgets?month=${month}`);
  assert.equal(budgetTotals.body.totalSpent,560);
  const income = await owner.post('/api/transactions').send({title:'Payday',amount:1000,type:'income',category:'Salary',paymentMethod:'Bank transfer',date:today});
  assert.equal(income.status,201);
  const summary = await owner.get(`/api/analytics/summary?month=${month}`);
  assert.equal(summary.body.income,1000);
  assert.equal(summary.body.expenses,560);
  assert.equal(summary.body.balance,440);
  const categories = await owner.get(`/api/analytics/categories?month=${month}`);
  assert.equal(categories.body.categories[0].amount,500);
  const trends = await owner.get('/api/analytics/monthly-trends');
  assert.equal(trends.body.savings.find(row=>row.month===month).amount,440);
  const recurring = await owner.post('/api/recurring').send({title:'Daily tea',amount:50,type:'expense',category:'Food and dining',paymentMethod:'Cash',frequency:'daily',startDate:today});
  assert.equal(recurring.status,201);
  await owner.get('/api/transactions');
  await owner.get('/api/transactions');
  const occurrences = await owner.get('/api/transactions');
  assert.equal(occurrences.body.transactions.filter(t=>t.title==='Daily tea').length,1);
  const monthEnd = await owner.post('/api/recurring').send({title:'Month end',amount:10,type:'expense',category:'Bills and utilities',paymentMethod:'Bank transfer',frequency:'monthly',startDate:'2024-01-31'});
  assert.equal(monthEnd.status,201);
  const monthEndTransactions = await owner.get('/api/transactions');
  const monthEndDates = monthEndTransactions.body.transactions.filter(t=>t.title==='Month end').map(t=>t.date);
  assert.ok(monthEndDates.includes('2024-02-29'));
  assert.ok(monthEndDates.includes('2024-03-31'));
  const goal = await owner.post('/api/goals').send({ title: 'Laptop', target: 80000, saved: 25000, targetDate: '2027-06-01' });
  assert.equal(goal.status, 201);
  const goals = await owner.get('/api/goals');
  assert.equal(goals.body.goals[0].remaining, 55000);
  assert.equal(goals.body.goals[0].percent, 31.3);
  const csv = await owner.get(`/api/reports/export.csv?from=${month}-01&to=${today}`);
  assert.equal(csv.status, 200);
  assert.match(csv.text, /Dinner/);
  assert.equal((await owner.delete(`/api/transactions/${txId}`)).status, 204);
});

test('reject duplicate accounts and malformed transaction submissions', async () => {
  const agent = request.agent(app);
  assert.equal((await agent.post('/api/auth/register').send({ name: 'Mina', email: 'mina@example.test', password: 'long-enough-password' })).status, 201);
  assert.equal((await request(app).post('/api/auth/register').send({ name: 'Mina', email: 'mina@example.test', password: 'long-enough-password' })).status, 409);
  assert.equal((await agent.post('/api/transactions').send({ title: '', amount: -1 })).status, 400);
});
